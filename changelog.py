def latest() -> Release:
    return RELEASES[0]


def as_dict() -> dict:
    return {
        "latest": latest().version,
        "kinds": {
            key: {"emoji": emoji, "label": label}
            for key, (emoji, label) in KINDS.items()
        },
        "releases": [
            {
                "version": release.version,
                "date": release.date,
                "title": release.title,
                "summary": release.summary,
                "items": [
                    {"kind": kind, "text": text}
                    for kind, text in release.items
                ],
            }
            for release in RELEASES
        ],
    }
