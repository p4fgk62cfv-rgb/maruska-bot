const SEEN_KEY = 'arena.newsSeen';
const LATEST = NEWS[0]!.id;
const listeners = new Set<() => void>();

function seenId(): number {
  return safeStorage.get<number>(SEEN_KEY, 0);
}

/** Days of news the player has not opened yet. */
export function useUnseenNews(): number {
  const [seen, setSeen] = useState(seenId);
  useEffect(() => {
    const update = () => setSeen(seenId());
    listeners.add(update);
    return () => void listeners.delete(update);
  }, []);
  return NEWS.filter((d) => d.id > seen).length;
}

/** The news screen was opened: everything up to now is read. Returns what was unread before. */
export function markNewsSeen(): number {
  const before = seenId();
  if (before !== LATEST) {
    safeStorage.set(SEEN_KEY, LATEST);
    for (const l of listeners) l();
  }
  return before;
}

export function newsDate(date: string): string {
  return new Date(`${date}T12:00:00`).toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' });
}
