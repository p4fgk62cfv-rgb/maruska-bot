def _parse(block: str) -> tuple[str, ...]:
    words = []
    for line in block.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        # "день рождения" и "чёрная дыра" — составные, оставляем целиком
        if line in ("день рождения", "чёрная дыра", "закадровый голос"):
            words.append(line)
            continue
        words.extend(line.split())
    return tuple(words)


