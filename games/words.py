_WORD_RE = re.compile(r"[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z\-]*")


def normalize(value: str) -> str:
    return value.lower().replace("ё", "е").strip()


def _same_root(guess: str, target: str) -> bool:
    """
    Сравнение с допуском на падежи: "кошку" засчитывается за "кошка".
    """
    if guess == target:
        return True

    # Короткие слова сравниваем целиком, длинные — по корню
    if len(target) <= 4:
        return False

    root = len(target) - 2

    if len(guess) < root:
        return False

    return guess[:root] == target[:root] and abs(len(guess) - len(target)) <= 3


def is_correct_guess(text: str | None, word: str) -> bool:
    if not text or not word:
        return False

    target = normalize(word)
    words = [normalize(w) for w in _WORD_RE.findall(text)]

    if not words:
        return False

    # Составное слово ищем целой фразой
    if " " in target:
        return target in " ".join(words)

    return any(_same_root(w, target) for w in words)
