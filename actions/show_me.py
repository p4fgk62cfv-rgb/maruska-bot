# Недавние подписи не повторяем, пока не пройдёт хотя бы столько других
RECENT_CAPTIONS = 25
_recent: deque[str] = deque(maxlen=RECENT_CAPTIONS)


def pick_caption(name: str, monkey: bool = False) -> str:
    pool = MONKEY_CAPTIONS if monkey else CAPTIONS
    fresh = [caption for caption in pool if caption not in _recent]
    caption = random.choice(fresh or pool)
    _recent.append(caption)
    return caption.format(name=name)
