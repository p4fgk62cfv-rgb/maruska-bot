"""
Фразы для действий.

Каждое действие описывается случайной фразой из своего набора,
поэтому одно и то же «Пиво» два раза подряд выглядит по-разному.

Синтаксис шаблона:
    {emoji}         эмодзи действия
    {actor}         кто сделал (именительный)
    {actor_gen}     от кого? от Стаса
    {actor_dat}     спасибо кому? Стасу
    {target}        кому (именительный)
    {target_acc}    винительный    — обнял кого? Люду
    {target_dat}    дательный      — подарил кому? Люде
    {target_gen}    родительный    — для кого? Люды
    {target_instr}  творительный   — с кем? Людой
    {item}          предмет в винительном      — принёс пиво
    {item_instr}    предмет в творительном     — угостил пивом
    <угостил|угостила>   форма глагола по роду того, кто действует

Если род определить не удалось, берётся форма «угостил(а)».
"""

import random
import re


VERB_RE = re.compile(r"<([^<>|]+)\|([^<>|]+)>")


def verb_form(male: str, female: str, gender: str) -> str:
    if gender == "male":
        return male
    if gender == "female":
        return female

    # Род неизвестен: склеиваем по общему началу.
    # обнял + обняла  -> обнял(а)
    # нашёл + нашла   -> нашёл(ла)
    common = 0
    for a, b in zip(male, female):
        if a != b:
            break
        common += 1

    tail = female[common:]

    if tail:
        return f"{male}({tail})"

    return male


def render(template: str, gender: str, **values) -> str:
    text = VERB_RE.sub(
        lambda match: verb_form(match.group(1), match.group(2), gender),
        template,
    )
    return text.format(**values)


