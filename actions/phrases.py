FALLBACK = (
    "{emoji} {actor} и {target} что-то затеяли ♡",
)


def templates_for(action) -> tuple:
    """Все встроенные фразы действия."""
    if action.category == "library":
        import library_core

        return library_core.phrases_for(action)

    if action.category == "call":
        options = CALLS.get(action.key)
    elif action.category == "pair":
        options = PAIR.get(action.key)
    else:
        # Свои фразы угощения — первыми, за ними общие фразы категории
        options = tuple(ITEM_PHRASES.get(action.key, ())) + tuple(CATEGORY_PHRASES.get(action.category, ()))

    return tuple(options) if options else tuple(FALLBACK)


def pick_template(action, hidden=None) -> str:
    """Случайная встроенная фраза, кроме скрытых в группе."""
    options = templates_for(action)

    if hidden:
        visible = [t for t in options if t not in hidden]
        # Скрыли всё — лучше старая фраза, чем действие без текста
        options = visible or options

    # Свои фразы угощения выпадают чаще общих: в половине случаев берём из них
    own = [t for t in ITEM_PHRASES.get(getattr(action, "key", ""), ()) if t in options]
    if own and random.random() < 0.5:
        return random.choice(own)
    return random.choice(options)
