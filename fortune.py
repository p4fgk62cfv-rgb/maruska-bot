MAX_TRIGGER_WORDS = 5

_WORDS_RE = re.compile(r"[А-Яа-яЁёA-Za-z]+")


def mentions_fortune(text: str | None) -> bool:
    if not text or text.startswith("/"):
        return False

    lowered = " ".join(text.lower().replace("ё", "е").split())

    if not any(t.replace("ё", "е") in lowered for t in TRIGGERS):
        return False

    return len(_WORDS_RE.findall(text)) <= MAX_TRIGGER_WORDS


# Сколько последних предсказаний помним, чтобы не повторяться
HISTORY_SIZE = 12

_history: dict[int, deque] = defaultdict(lambda: deque(maxlen=HISTORY_SIZE))


def _pick(pool: tuple[str, ...], seen: deque) -> str:
    fresh = [text for text in pool if text not in seen]

    # Если человек вычерпал весь список — начинаем круг заново
    return random.choice(fresh or list(pool))


def predict(user_id: int, name: str, mode: str = "roast", category: str = "more") -> str:
    """
    Генерирует предсказание по режиму/категории.
    История общая для пользователя, чтобы не повторяться подряд.
    """
    seen = _history[user_id]

    pools = {
        "more": {
            "normal": SERIOUS,
            "roast": FUNNY,
            "vulgar": VULGAR,
            "brutal": BRUTAL,
        },
        "love": LOVE,
        "money": MONEY,
        "vulgar": VULGAR,
        "roast": ROAST,
        "brutal": BRUTAL,
    }

    selected = pools.get(category, pools["more"])

    if isinstance(selected, dict):
        pool = selected.get(mode, selected["roast"])

        # Режим с подъёбом разбавляется серьёзными — доля FUNNY_RATIO
        if pool is FUNNY and random.random() >= FUNNY_RATIO:
            pool = SERIOUS
    else:
        pool = selected

    text = _pick(pool, seen)
    seen.append(text)

    intro = random.choice(INTROS)
    return f"{intro.format(name=name)}\n\n{text}"

def reset_history(user_id: int | None = None) -> None:
    """
    Сброс памяти о выданных предсказаниях (нужен тестам).
    """
    if user_id is None:
        _history.clear()
    else:
        _history.pop(user_id, None)
